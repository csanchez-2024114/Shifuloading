"""Interfaces de la base de negocio (usuarios, sesiones, propiedad de conversaciones, intentos de login). El resto del
código solo usa estas interfaces: cambiar de motor es escribir otra implementación (ver mongo.py y memory.py).
Nada de aquí guarda mensajes, resúmenes ni recuerdos: eso vive en la base de la IA."""
from datetime import datetime
from typing import Protocol


class DuplicateEmail(Exception):
    """Ya existe un usuario con ese correo."""


class UsersRepo(Protocol):
    def create(self, user_id: str, email: str, display_name: str, password_hash: str) -> dict: ...
    def get(self, user_id: str) -> dict | None: ...
    def get_by_email(self, email: str) -> dict | None: ...
    def delete(self, user_id: str) -> None: ...


class SessionsRepo(Protocol):
    def create(self, token_hash: str, user_id: str, expires_at: datetime) -> None: ...
    def get(self, token_hash: str) -> dict | None: ...
    def touch(self, token_hash: str, expires_at: datetime) -> None: ...
    def delete(self, token_hash: str) -> None: ...
    def delete_for_user(self, user_id: str) -> None: ...


class ThreadsRepo(Protocol):
    def create(self, thread_id: str, user_id: str, title: str = "") -> dict: ...
    def get(self, thread_id: str) -> dict | None: ...
    def touch(self, thread_id: str, title: str | None = None) -> None: ...
    def rename(self, thread_id: str, title: str) -> None: ...
    def list_for_user(self, user_id: str) -> list[dict]: ...
    def delete(self, thread_id: str) -> None: ...
    def delete_for_user(self, user_id: str) -> None: ...


class AttemptsRepo(Protocol):
    """Fallos de login por clave ("email:<correo>" o "ip:<ip>") y bloqueos temporales."""
    def record_failure(self, key: str, at: datetime) -> None: ...
    def failures_since(self, key: str, since: datetime) -> int: ...
    def lock(self, key: str, until: datetime) -> None: ...
    def locked_until(self, key: str) -> datetime | None: ...
    def clear(self, key: str) -> None: ...


class AppData(Protocol):
    users: UsersRepo
    sessions: SessionsRepo
    threads: ThreadsRepo
    attempts: AttemptsRepo
